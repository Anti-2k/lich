package dev.lich.compat.lwjgl2.generator;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.Type;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.MethodNode;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Writes {@code renames.txt}: for every public static OpenGL/OpenAL method of LWJGL 2 that LWJGL 3 no
 * longer has, the LWJGL 3 method that does the same under LWJGL 3's naming, if there is one with the same
 * parameters. LWJGL 2 left the type out of names where the buffer argument implies it and LWJGL 3 spells
 * it like the C function, so {@code glGetFloat(int, FloatBuffer)} is {@code glGetFloatv},
 * {@code glUniform1(int, IntBuffer)} is {@code glUniform1iv} and {@code glGetShader(int, int)} returning
 * an int is {@code glGetShaderi}. A {@code String} parameter may be a {@code CharSequence} in LWJGL 3.
 *
 * <p>Arguments: the LWJGL 2 jar and the output file. LWJGL 3 comes from this program's class path.
 */
public final class RenameGenerator {
    /** LWJGL 2 classes LWJGL 3 doesn't have, and the LWJGL 3 class that has their methods. */
    private static final Map<String, String> MOVED_OWNERS = Map.of(
            "org/lwjgl/opengl/ARBBufferObject", "org/lwjgl/opengl/ARBVertexBufferObject",
            "org/lwjgl/opengl/ARBPixelBufferObject", "org/lwjgl/opengl/ARBVertexBufferObject",
            "org/lwjgl/opengl/ARBProgram", "org/lwjgl/opengl/ARBVertexProgram",
            "org/lwjgl/opengl/ARBFragmentProgram", "org/lwjgl/opengl/ARBVertexProgram",
            "org/lwjgl/openal/EFX10", "org/lwjgl/openal/EXTEfx");

    private static final List<String> EXTENSION_SUFFIXES = List.of("ARB", "EXT", "NV", "ATI", "AMD", "APPLE", "KHR", "INTEL");

    private RenameGenerator() {
    }

    public static void main(String[] args) throws IOException {
        Map<String, ClassNode> lwjgl2 = readJar(Path.of(args[0]));
        Map<String, ClassNode> lwjgl3 = new HashMap<>();
        Set<String> lines = new TreeSet<>();
        Set<String> unmapped = new TreeSet<>();
        int missing = 0;
        for (ClassNode type : lwjgl2.values()) {
            if (!type.name.matches("org/lwjgl/(opengl|openal)/[A-Za-z0-9]+") || (type.access & Opcodes.ACC_PUBLIC) == 0) {
                continue;
            }
            String owner3 = MOVED_OWNERS.getOrDefault(type.name, type.name);
            List<MethodNode> methods3 = methods(lwjgl3, owner3, RenameGenerator::lwjgl3Class);
            if (methods3.isEmpty()) {
                continue;
            }
            Set<String> present = new java.util.HashSet<>();
            if (owner3.equals(type.name)) {
                methods3.forEach(method -> present.add(method.name + method.desc));
            }
            for (MethodNode method : methods(lwjgl2, type.name, lwjgl2::get)) {
                if ((method.access & (Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC)) != (Opcodes.ACC_PUBLIC | Opcodes.ACC_STATIC)
                        || present.contains(method.name + method.desc)) {
                    continue;
                }
                missing++;
                MethodNode target = find(methods3, method);
                if (target != null) {
                    lines.add(type.name + " " + method.name + " " + method.desc + " " + owner3 + " " + target.name + " " + target.desc);
                } else {
                    unmapped.add("# " + type.name + " " + method.name + " " + method.desc);
                }
            }
        }
        List<String> out = new ArrayList<>();
        out.add("# Generated by RenameGenerator (./gradlew :compat-lwjgl2:generateRenames). Don't edit.");
        out.add("# LWJGL 2 owner, name, descriptor -> LWJGL 3 owner, name, descriptor; all static.");
        out.add("# " + lines.size() + " of the " + missing + " static methods LWJGL 3 dropped; the rest need hand-written mirrors.");
        out.addAll(lines);
        out.add("");
        out.add("# No rename found; Lwjgl2Compat's mirrors cover the ones the game and mods call:");
        out.addAll(unmapped);
        Files.write(Path.of(args[1]), out);
        System.out.println("Wrote " + lines.size() + " renames (" + missing + " missing methods) to " + args[1]);
    }

    /** The LWJGL 3 method that {@code method} became, or {@code null}. */
    private static MethodNode find(List<MethodNode> candidates, MethodNode method) {
        String descriptor = method.desc.replace("Ljava/lang/String;", "Ljava/lang/CharSequence;");
        for (String name : names(method)) {
            for (MethodNode candidate : candidates) {
                if ((candidate.access & Opcodes.ACC_STATIC) != 0 && candidate.name.equals(name)
                        && (candidate.desc.equals(method.desc) || candidate.desc.equals(descriptor))) {
                    return candidate;
                }
            }
        }
        return null;
    }

    /** Names LWJGL 3 may use for {@code method}, most likely first. */
    private static List<String> names(MethodNode method) {
        String base = method.name;
        String extension = "";
        for (String suffix : EXTENSION_SUFFIXES) {
            if (base.endsWith(suffix)) {
                extension = suffix;
                base = base.substring(0, base.length() - suffix.length());
                break;
            }
        }
        Type[] parameters = Type.getArgumentTypes(method.desc);
        String last = parameters.length == 0 ? "" : parameters[parameters.length - 1].getDescriptor();
        String type = switch (last) {
            case "Ljava/nio/FloatBuffer;" -> "f";
            case "Ljava/nio/IntBuffer;" -> "i";
            case "Ljava/nio/DoubleBuffer;" -> "d";
            case "Ljava/nio/ShortBuffer;" -> "s";
            case "Ljava/nio/ByteBuffer;" -> "b";
            case "Ljava/nio/LongBuffer;" -> "i64";
            default -> null;
        };
        Set<String> names = new LinkedHashSet<>();
        names.add(method.name);
        if (type != null) {
            names.add(base + type + "v" + extension);
            names.add(base + type + extension);
            names.add(base + type + "_v" + extension);
            names.add(base + "v" + extension);
        } else {
            // A getter returning one value: glGetShader(int, int) → glGetShaderi.
            String returned = switch (Type.getReturnType(method.desc).getSort()) {
                case Type.INT, Type.BOOLEAN -> "i";
                case Type.FLOAT -> "f";
                case Type.DOUBLE -> "d";
                case Type.LONG -> "i64";
                default -> null;
            };
            if (returned != null) {
                names.add(base + returned + extension);
            }
        }
        return List.copyOf(names);
    }

    /** {@code owner}'s methods and its superclasses', or none if {@code lookup} doesn't know it. */
    private static List<MethodNode> methods(Map<String, ClassNode> cache, String owner,
                                            java.util.function.Function<String, ClassNode> lookup) {
        List<MethodNode> methods = new ArrayList<>();
        for (String name = owner; name != null; ) {
            ClassNode type = cache.computeIfAbsent(name, lookup);
            if (type == null) {
                break;
            }
            methods.addAll(type.methods);
            name = type.superName;
        }
        return methods;
    }

    private static ClassNode lwjgl3Class(String name) {
        try (InputStream in = ClassLoader.getSystemResourceAsStream(name + ".class")) {
            return in == null ? null : read(in.readAllBytes());
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static Map<String, ClassNode> readJar(Path jar) throws IOException {
        Map<String, ClassNode> classes = new HashMap<>();
        try (ZipFile zip = new ZipFile(jar.toFile())) {
            for (ZipEntry entry : Collections.list(zip.entries())) {
                if (entry.getName().endsWith(".class")) {
                    try (InputStream in = zip.getInputStream(entry)) {
                        ClassNode type = read(in.readAllBytes());
                        classes.put(type.name, type);
                    }
                }
            }
        }
        return classes;
    }

    private static ClassNode read(byte[] bytes) {
        ClassNode type = new ClassNode();
        new ClassReader(bytes).accept(type, ClassReader.SKIP_CODE);
        return type;
    }
}
