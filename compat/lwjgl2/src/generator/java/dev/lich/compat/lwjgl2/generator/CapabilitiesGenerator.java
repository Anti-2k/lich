package dev.lich.compat.lwjgl2.generator;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.zip.ZipFile;

/**
 * Writes {@code org/lwjgl/opengl/ContextCapabilities.java}: LWJGL 2's capability flags (one public final
 * boolean per GL version and extension), each copied from the LWJGL 3 {@code GLCapabilities} field of the
 * same name, or, for extensions LWJGL 3 doesn't know, taken from the context's extension list.
 *
 * <p>Arguments: the LWJGL 2 jar and the output file. LWJGL 3 comes from this program's class path.
 */
public final class CapabilitiesGenerator {
    private static final String BOOLEAN = "Z";

    private CapabilitiesGenerator() {
    }

    public static void main(String[] args) throws IOException {
        List<String> lwjgl2;
        try (ZipFile jar = new ZipFile(args[0]);
             InputStream in = jar.getInputStream(jar.getEntry("org/lwjgl/opengl/ContextCapabilities.class"))) {
            lwjgl2 = booleanFields(in.readAllBytes());
        }
        Set<String> lwjgl3;
        try (InputStream in = ClassLoader.getSystemResourceAsStream("org/lwjgl/opengl/GLCapabilities.class")) {
            lwjgl3 = new HashSet<>(booleanFields(in.readAllBytes()));
        }

        List<String> out = new ArrayList<>();
        out.add("package org.lwjgl.opengl;");
        out.add("");
        out.add("import java.util.HashSet;");
        out.add("import java.util.Set;");
        out.add("");
        out.add("/**");
        out.add(" * LWJGL 2's capability flags for one context, read from LWJGL 3's {@link GLCapabilities}; extensions");
        out.add(" * LWJGL 3 doesn't know come from the context's extension list.");
        out.add(" *");
        out.add(" * <p>Generated by CapabilitiesGenerator (./gradlew :compat-lwjgl2:generateCapabilities). Don't edit.");
        out.add(" */");
        out.add("public class ContextCapabilities {");
        for (String field : lwjgl2) {
            out.add("    public final boolean " + field + ";");
        }
        out.add("");
        out.add("    ContextCapabilities(GLCapabilities caps) {");
        if (lwjgl2.stream().anyMatch(field -> !lwjgl3.contains(field))) {
            out.add("        Set<String> extensions = extensions(caps);");
        }
        for (String field : lwjgl2) {
            out.add("        " + field + " = " + (lwjgl3.contains(field) ? "caps." + field : "extensions.contains(\"" + field + "\")") + ";");
        }
        out.add("    }");
        out.add("");
        out.add("    private static Set<String> extensions(GLCapabilities caps) {");
        out.add("        Set<String> extensions = new HashSet<>();");
        out.add("        if (caps.OpenGL30) {");
        out.add("            int count = GL11.glGetInteger(GL30.GL_NUM_EXTENSIONS);");
        out.add("            for (int i = 0; i < count; i++) {");
        out.add("                extensions.add(GL30.glGetStringi(GL11.GL_EXTENSIONS, i));");
        out.add("            }");
        out.add("        } else {");
        out.add("            String all = GL11.glGetString(GL11.GL_EXTENSIONS);");
        out.add("            if (all != null) {");
        out.add("                extensions.addAll(java.util.Arrays.asList(all.trim().split(\"\\\\s+\")));");
        out.add("            }");
        out.add("        }");
        out.add("        return extensions;");
        out.add("    }");
        out.add("}");
        Files.write(Path.of(args[1]), out);
        long fromExtensions = lwjgl2.stream().filter(field -> !lwjgl3.contains(field)).count();
        System.out.println("Wrote " + lwjgl2.size() + " capabilities (" + fromExtensions + " from the extension list) to " + args[1]);
    }

    /** The public boolean fields, in declaration order. */
    private static List<String> booleanFields(byte[] classFile) {
        ClassNode node = new ClassNode();
        new ClassReader(classFile).accept(node, ClassReader.SKIP_CODE);
        List<String> fields = new ArrayList<>();
        for (FieldNode field : node.fields) {
            if ((field.access & Opcodes.ACC_PUBLIC) != 0 && (field.access & Opcodes.ACC_STATIC) == 0 && field.desc.equals(BOOLEAN)) {
                fields.add(field.name);
            }
        }
        return fields;
    }
}
